from typing import ClassVar

from PyQt6.QtGui import QColor


def _qss_color(value: str) -> str:
    """Convert a painter-safe ``#RRGGBB``/``#AARRGGBB`` token into a QSS color."""
    if len(value) == 9:
        alpha = int(value[1:3], 16)
        red, green, blue = (int(value[i : i + 2], 16) for i in (3, 5, 7))
        return f"rgba({red}, {green}, {blue}, {alpha})"
    return value


def _tint(value: str, alpha: int) -> str:
    """Return a translucent QSS ``rgba(...)`` version of a ``#RRGGBB`` token."""
    red, green, blue = (int(value[i : i + 2], 16) for i in (1, 3, 5))
    return f"rgba({red}, {green}, {blue}, {alpha})"


