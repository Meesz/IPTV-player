    @classmethod
    def get_dark_theme(cls) -> str:
        return cls._build_theme(cls._DARK)

    @classmethod
    def get_light_theme(cls) -> str:
        return cls._build_theme(cls._LIGHT)

    @classmethod
    def tokens(cls, mode: str) -> dict:
        return cls._LIGHT if mode == "light" else cls._DARK

    @classmethod
    def color(cls, mode: str, key: str) -> QColor:
        """Return a valid ``QColor`` for a token; raise ``KeyError`` for unknown keys."""
        color = QColor(cls.tokens(mode)[key])
        if not color.isValid():
            raise ValueError(f"Theme token {key!r} is not a valid color")
        return color

